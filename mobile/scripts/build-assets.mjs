// Copies what the app shares with the desktop into src/generated/ (not committed; runs on npm install and before tests):
//   library.json      coach/library.json, the exercise catalogue
//   assessments.json  coach/assessments.json, the calibration tests
//   pictures.json     name, credit, steps and image links for every picture the library and the tests use
//                     (Everkinetic drawings, CC BY-SA 4.0; free-exercise-db photos, public domain). Images load from
//                     their sources on demand and stay in the phone's image cache; none ship with the app.
//   knowledge.ts      coach/knowledge/*.md, the Coach's reference modules
//   templates.json    templates/plan, the starter plan
// The repository is the single source: never edit src/generated by hand.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, "..", "..");
const OUT = join(HERE, "..", "src", "generated");
const read = p => JSON.parse(readFileSync(join(REPO, p), "utf8").replace(/^﻿/, ""));
const write = (name, text) => writeFileSync(join(OUT, name), text);

mkdirSync(OUT, { recursive: true });
const library = read("coach/library.json");
const assessments = read("coach/assessments.json");
write("library.json", JSON.stringify(library));
write("assessments.json", JSON.stringify(assessments));

const FREE = "https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/";
const EK = "https://raw.githubusercontent.com/everkinetic/data/main/dist/svg/";
const catalogue = {};
for (const x of read("coach/exercises/exercises.json")) {
  catalogue[x.id] = { name: x.name, credit: "Public domain (Unlicense), free-exercise-db", instructions: x.instructions || [],
    images: (x.images || []).map(p => FREE + p) };
}
for (const x of read("coach/exercises/everkinetic.json")) {
  if (!x.img) continue; // no drawings for this one upstream
  catalogue["ek-" + x.name] = { name: x.title, credit: "CC BY-SA 4.0, Everkinetic", instructions: x.steps || [],
    images: [`${EK}${x.id_num}-relaxation.svg`, `${EK}${x.id_num}-tension.svg`] };
}
const wanted = new Set();
for (const e of library.exercises) if (e.picture) wanted.add(e.picture);
for (const t of Object.values(assessments.tests)) if (t.lib) wanted.add(t.lib);
const templateRoutines = Object.fromEntries(readdirSync(join(REPO, "templates/plan/routines"))
  .filter(f => f.endsWith(".json")).map(f => [f.replace(/\.json$/, ""), read("templates/plan/routines/" + f)]));
for (const r of Object.values(templateRoutines)) for (const e of r.exercises || []) if (e.lib) wanted.add(e.lib);
const pictures = {}, missing = [];
for (const id of [...wanted].sort()) {
  if (catalogue[id]) pictures[id] = catalogue[id];
  else missing.push(id);
}
write("pictures.json", JSON.stringify(pictures));
if (missing.length) console.warn("build-assets: no picture catalogue entry for", missing.join(", "));

const knowledge = {};
for (const f of readdirSync(join(REPO, "coach/knowledge")).filter(f => f.endsWith(".md")).sort()) {
  knowledge[f.replace(/\.md$/, "")] = readFileSync(join(REPO, "coach/knowledge", f), "utf8");
}
write("knowledge.ts", "// Generated by scripts/build-assets.mjs from coach/knowledge/*.md. Don't edit.\n"
  + `export const KNOWLEDGE: Record<string, string> = ${JSON.stringify(knowledge, null, 1)};\n`);

write("templates.json", JSON.stringify({ rolling: read("templates/plan/rolling.json"), routines: templateRoutines }));
console.log(`build-assets: ${library.exercises.length} exercises, ${Object.keys(assessments.tests).length} tests, `
  + `${Object.keys(pictures).length} pictures, ${Object.keys(knowledge).length} knowledge modules`);
